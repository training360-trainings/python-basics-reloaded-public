print(10 + 20)
# operandus: egy érték vagy változó, amely részt vesz egy műveletben: 10 és 20
# operátor: egy olyan szimbólum vagy kulcsszó, amely egy műveletet hajt végre az operandusokon: +
# kifejezés: egy olyan kódrészlet ami egy értéket ad vissza

summa = 10 + 20
# utasítás: egy olyan kódrészlet, amely egy vagy több műveletet hajt végre, de nem ad vissza értéket
# oeprandus: 10, 20
# operátor: +, =
# kifejezés: 10 + 20
# utasítás: summa = 10 + 20
